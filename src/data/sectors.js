export function getSectorBySlug(slug) {
  return sectors.find((s) => s.slug === slug) || null
}

export function getSubSectorBySlug(sectorSlug, subSectorSlug) {
  const sector = getSectorBySlug(sectorSlug)
  if (!sector) return null
  return sector.subSectors.find((ss) => ss.slug === subSectorSlug) || null
}

export function getSectorNameBySlug(slug) {
  const sector = getSectorBySlug(slug)
  return sector ? sector.name : null
}
